# ======================== 详细地址正则 ========================

# 开发区/新区后缀黑名单（用于区县兜底正则的排除）
_DEV_ZONE_SUFFIXES = {
    "开发区", "园区", "新区", "保税区", "自贸区", "出口加工区",
    "保税港区", "度假区", "风景区", "名胜区", "工业区",
}

# 开发区 / 经济开发区 / 高新区 / 工业园区 / 自贸区 等
# 格式：[前缀0-15字][开发区类型后缀]
# 前缀允许 0 长度，以支持 "高新区"、"工业园区" 等独立出现的简短开发区名
# 负向前瞻 (?!路|街|...) 防止 "科技园南路" 中的 "科技园" 被误匹配
RE_DEV_ZONE = re.compile(
    r'([一-龥]{0,15}'
    r'(?:经济技术开发区|经济开发区|高新技术产业开发区|'
    r'高新科技产业开发区|高新产业开发区|'
    r'高新区|自贸区|保税区|保税港区|'
    r'工业园区|工业园|科技园区|科技园|产业园区|产业园|'
    r'出口加工区|旅游度假区|风景名胜区|'
    r'高科技园区|生态园区|'
    r'开发区))'
    r'(?!路|街|道|巷|弄|里|号|[东南西北]路|[东南西北]街|[东南西北]道)'
)

# 地标建筑 / 公司 / 大厦
# 格式：[名称2-25字][地标后缀]
# 注意：科技园/产业园等与开发区后缀重叠，但开发区先提取，
# 剩余文本中的科技园即为地标级（如"国际科技园"）
RE_LANDMARK = re.compile(
    r'([一-龥a-zA-Z\d]{2,25}'
    r'(?:总部|大厦|中心|广场|大楼|商城|商场|'
    r'酒店|饭店|医院|学校|学院|大学|中学|小学|'
    r'工厂|基地|研究院|集团|公司|'
    r'科技园|科学园|产业园|创业园|创新园|科创园|高新园|'
    r'软件园|创意园|生态港|科技港|'
    r'微电子港|电子港|数码港|'
    r'时代广场|城市广场|国际中心))'
)

# 街道/镇/乡
RE_TOWNSHIP = re.compile(
    r'([一-龥]{2,8}(?:街道|镇|乡|民族乡|苏木|民族镇))'
)

# 路/大道/大街/道/巷/弄/条/胡同/里
# 注意：前缀用 [一-龥a-zA-Z] 排除数字，避免吞噬门牌号
# (?<!街)道 防止"街道"中的"道"被误匹配为路名
# 街(?!道) 防止"望京街道"中的"望京街"被误匹配为路名
RE_ROAD = re.compile(
    r'([一-龥a-zA-Z]{2,30}'
    r'(?:大道|大街|(?<!街)道|路|巷|弄|条|胡同|里|'
    r'街(?!道))'
    r'(?:[东南西北中]段|\d+段)?)'
)

# 社区/小区/花园/苑/公寓/新城/新村/嘉园/佳园/名苑/雅苑/华庭/豪庭/家园/花苑
RE_COMMUNITY = re.compile(
    r'([一-龥\w]{2,25}(?:小区|花园|花苑|苑|公寓|新城|新村|嘉园|佳园'
    r'|名苑|雅苑|华庭|豪庭|家园|新苑|东区|西区|南区|北区|中区))'
)

# 村/庄/屯
RE_VILLAGE = re.compile(
    r'([一-龥]{1,10}(?:村|庄|屯|寨|堡|营|集))'
)

# 号（门牌号，但不匹配 X号楼 中的 X号——那是楼栋号）
RE_DOOR_NUMBER = re.compile(r'(\d{1,6}号(?!楼))')

# 栋/号楼/座/幢（支持 B座 纯字母、B1栋 字母+数字、3号楼 纯数字）
RE_BUILDING = re.compile(
    r'((?:[A-Za-z]{1,3}|[A-Za-z]?\d{1,4}|[一-龥]{1,6})(?:号楼|栋|幢|座))'
)

# 单元/门
RE_UNIT = re.compile(r'(\d{1,4}(?:单元|门|弄))')

# 层/楼/室（含显式后缀）
RE_FLOOR_ROOM = re.compile(
    r'((?:\d{1,4}|[一二三四五六七八九十百千]+)(?:层|楼|室|房间|号房))'
)

# 纯数字室号（末尾无后缀的 2-4 位数字，如 "501"、"2301"）
# 仅在文本末尾或后跟非数字非字母字符时匹配
RE_BARE_ROOM = re.compile(r'(?<!\d)(\d{2,4})(?!\d|[一-龥a-zA-Z])')

# 邮编
RE_POSTCODE = re.compile(r'(\d{6})')

# 区县兜底正则（词典未覆盖的区县用正则匹配）
RE_DISTRICT_FALLBACK = re.compile(
    r'^([一-龥]{1,10}(?:区|县|市|旗|自治县|自治旗|特区|林区))'
)


# ======================== 工具函数 ========================


def _strip_province_suffix(name: str) -> str:
    """去掉省份名称的后缀，返回纯省名。"""
    for suffix in _PROVINCE_SUFFIXES:
        if name.endswith(suffix):
            return name[:-len(suffix)]
    return name


def _strip_city_suffix(name: str) -> str:
    """去掉城市名称的后缀，返回纯市名。"""
    for suffix in ["市", "自治州", "地区", "盟"]:
        if name.endswith(suffix) and name not in ("长春市",):  # 长春市特殊处理
            return name[:-len(suffix)]
    return name


def _fmm_match(text: str, start: int, candidates: list[str]) -> tuple[Optional[str], int]:
    """
    正向最大匹配 (Forward Maximum Matching)。

    在 text[start:] 位置，从 candidates 中选择最长的匹配项。
    candidates 必须按长度降序排列。

    Returns:
        (matched_string, match_length) 或 (None, 0) 如果无匹配。
    """
    remaining = text[start:]
    for cand in candidates:
        if remaining.startswith(cand):
            return cand, len(cand)
    return None, 0


def _try_match_district(text: str, start: int,
                        districts: list[str]) -> tuple[Optional[str], int]:
    """尝试在 text[start:] 匹配区县名，若词典未命中则尝试正则。"""
    # 先试词典
    cands = sorted(districts, key=len, reverse=True)
    match, length = _fmm_match(text, start, cands)
    if match:
        return match, length

    # 正则兜底（需排除开发区后缀伪装成区县的情况）
    m = RE_DISTRICT_FALLBACK.match(text[start:])
    if m:
        matched = m.group(1)
        # 黑名单：如果匹配到的内容是开发区/园区/新区等，拒绝作为区县
        for suffix in _DEV_ZONE_SUFFIXES:
            if matched.endswith(suffix) and matched != suffix:
                return None, 0
        return matched, len(matched)

    return None, 0


# ======================== 主解析函数 ========================


def parse_address(text: str) -> ParsedAddress:
    """
    解析中文地址字符串，返回结构化的 ParsedAddress。

    算法：
    1. 预处理：全角转半角数字、规范化空格、去除前后空白
    2. FMM 匹配：省 → 市 → 区/县
    3. 正则提取：街道 → 路 → 小区/村 → 号 → 栋/楼 → 单元 → 室/层
    4. 剩余文本放入 detail

    Examples:
        >>> parse_address("北京市朝阳区望京街道望京花园3号楼2单元501")
        ParsedAddress(province="北京", city="北京", district="朝阳区",
                      township="望京街道", community="望京花园", building="3号楼",
                      unit="2单元", room="501")

        >>> parse_address("广东省深圳市南山区科技园南路xx号")
        ParsedAddress(province="广东", city="深圳", district="南山区",
                      road="科技园南路")

        >>> parse_address("")
        ParsedAddress()
    """
    result = ParsedAddress(raw=text)

    if not text or not text.strip():
        return result

    # ---- 预处理 ----
    text = _normalize(text)
    pos = 0  # 当前匹配位置

    # ---- Phase A: FMM 行政区域匹配 ----

    # Step 1: 匹配省份
    province_candidates = sorted(ADMIN_DATA.keys(), key=len, reverse=True)
    province_key, prov_len = _fmm_match(text, 0, province_candidates)
    if not province_key:
        # 无法识别省份 → 整个字符串交给详细组件提取
        _extract_detail_components(result, text)
        if not result.detail and not result.road and not result.township:
            result.detail = text
        return result

    result.province = _strip_province_suffix(province_key)
    pos = prov_len

    # Step 2: 匹配城市
    cities = ADMIN_DATA[province_key]
    city_candidates = sorted(cities.keys(), key=len, reverse=True)

    city_key, city_len = _fmm_match(text, pos, city_candidates)
    if city_key:
        result.city = _strip_city_suffix(city_key)
        pos += city_len
    elif result.province in MUNICIPALITIES:
        # 直辖市：市=省，用 province_key 作为 city_key 以继续区县匹配
        result.city = result.province
        city_key = province_key
    else:
        # 未找到城市，跳到详细地址
        remaining = text[pos:]
        _extract_detail_components(result, remaining)
        if not result.detail and not result.road:
            result.detail = remaining
        return result

    # Step 3: 匹配区县
    if city_key:
        districts = cities.get(city_key, [])
        district_match, dist_len = _try_match_district(text, pos, districts)
        if district_match:
            result.district = district_match
            pos += dist_len

    # ---- Phase B: 正则提取详细地址 ----
    remaining = text[pos:].strip()
    if remaining:
        _extract_detail_components(result, remaining)

    return result


def _normalize(text: str) -> str:
    """预处理地址文本。"""
    # 全角数字转半角
    result = []
    for ch in text:
        if '０' <= ch <= '９':  # 全角数字 ０-９
            result.append(chr(ord(ch) - 0xfee0))
        elif ch == '　':  # 全角空格
            result.append(' ')
        else:
            result.append(ch)
    text = ''.join(result)

    # 去掉多余空白
    text = re.sub(r'\s+', ' ', text)
    return text.strip()


def _extract_detail_components(result: ParsedAddress, detail_text: str) -> None:
    """
    从详细地址文本中按顺序提取各组件。

    提取顺序（先粗后细）：
      邮编 → 开发区 → 街道/镇 → 路/街 → 小区/花园 → 村/庄 → 地标 → 门牌号 → 栋/楼 → 单元 → 室/层
    每个组件匹配后从文本中移除，避免重复匹配。
    """
    text = detail_text
    _pending_door = ""  # 暂存门牌号，等 road 匹配后附加

    # 邮编（优先级最高，先提取并移除）
    m = RE_POSTCODE.search(text)
    if m:
        text = _remove_match(text, m)

    # ---- 开发区 / 高新区 / 工业园区（在街道之前，防止路名吞噬开发区名） ----
    m = RE_DEV_ZONE.search(text)
    if m:
        result.development_zone = m.group(1)
        text = _remove_match(text, m)

    # ---- 按优先级依次提取（road 在 township 之前，防止路名被 township 吞噬） ----
    patterns = [
        ('door', RE_DOOR_NUMBER),
        ('road', RE_ROAD),
        ('township', RE_TOWNSHIP),
        ('community', RE_COMMUNITY),
        ('village', RE_VILLAGE),
        ('landmark', RE_LANDMARK),
        ('building', RE_BUILDING),
        ('unit', RE_UNIT),
        ('room', RE_FLOOR_ROOM),
        ('bare_room', RE_BARE_ROOM),
    ]

    for attr, pattern in patterns:
        m = pattern.search(text)
        if m:
            value = m.group(1)
            if attr == 'township':
                result.township = value
            elif attr == 'road':
                result.road = value
                # 如果之前有 pending 的门牌号，附加到路名后面
                if _pending_door:
                    result.road += _pending_door
            elif attr == 'community':
                result.community = value
            elif attr == 'village':
                # 村庄信息作为社区信息的补充
                if not result.community:
                    result.community = value
                else:
                    result.detail = value + result.detail
            elif attr == 'landmark':
                result.landmark = value
            elif attr == 'door':
                # 门牌号：如果路名已存在则附加，否则暂存
                if result.road:
                    result.road += value
                else:
                    _pending_door = value
                    text = _remove_match(text, m)
                    continue  # 跳过移除步骤，等 road 匹配后再追加
            elif attr == 'building':
                result.building = value
            elif attr == 'unit':
                result.unit = value
            elif attr == 'room':
                result.room = value
            elif attr == 'bare_room':
                if not result.room:
                    result.room = value + "室"
            text = _remove_match(text, m)

    # 如果 pending door 最终没有 road 来接收，放入 detail
    if _pending_door and not result.road:
        prefix = result.detail
        result.detail = _pending_door + prefix

    # 剩余文本放入 detail
    text = text.strip().strip('，,。.、 \t')
    if text:
        # 如果已有 detail 内容则前置
        prefix = result.detail
        result.detail = (text + prefix).strip()


def _remove_match(text: str, m: re.Match) -> str:
    """从文本中移除已匹配的部分。"""
    return text[:m.start()] + text[m.end():]


# ======================== 便捷函数 ========================


def parse_order_address(order_text: str) -> tuple[Optional[str], Optional[str], Optional[ParsedAddress]]:
    """
    从一段可能包含姓名、电话、地址的文本中提取并解析地址。

    这是一个便捷函数，组合了现有的 parser.parse_order() 和 parse_address()。
    如果 parser 模块可用则使用，否则做简单的电话/姓名提取。

    Returns:
        (name, phone, parsed_address)
    """
    try:
        from parser import parse_order as _parse_order
        order = _parse_order(order_text)
        name = order.name or None
        phone = order.phone or None
        addr = parse_address(order.address) if order.address else parse_address(order_text)
        return name, phone, addr
    except ImportError:
        # parser 不可用时的简易提取
        name = None
        phone = None
        # 简单的手机号提取
        m = re.search(r'1[3-9]\d{9}', order_text)
        if m:
            phone = m.group()
        addr = parse_address(order_text)
        return name, phone, addr


# ======================== 安全解析包装 ========================


def parse_address_safe(text: str) -> ParsedAddress:
    """
    安全解析中文地址 — 带异常保护和日志。

    保证永远不会抛出异常。解析失败时返回空的 ParsedAddress。

    Args:
        text: 待解析的地址字符串

    Returns:
        ParsedAddress 实例（保证不为 None）
    """
    import logging
    logger = logging.getLogger("moshidadan.address_parser")

    if not text or not isinstance(text, str):
        logger.debug("parse_address_safe: 输入为空或非字符串")
        return ParsedAddress(raw=str(text) if text else "")

    # 长度限制
    if len(text) > 10000:
        logger.warning("parse_address_safe: 输入文本过长(%d字符)，截断", len(text))
        text = text[:10000]

    try:
        return parse_address(text)
    except re.error as e:
        logger.error("parse_address_safe: 正则错误 — %s", e)
        return ParsedAddress(raw=text[:500])
    except Exception as e:
        logger.exception("parse_address_safe: 解析异常 — %s", e)
        return ParsedAddress(raw=text[:500])


