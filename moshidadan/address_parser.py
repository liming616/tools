"""
经典中文地址解析器 (Classic Chinese Address Parser)

算法：行政区域词典 + 正向最大匹配(FMM) + 正则详细地址分解
这是顺丰、京东物流、菜鸟等主流物流/电商公司使用的经典方法。

解析流程：
  1. 预处理（全角转半角、规范化）
  2. FMM 逐层匹配：省 → 市 → 区/县
  3. 正则提取详细地址：街道/镇 → 路/街 → 小区/花园 → 栋/楼 → 单元 → 室
  4. 组装 ParsedAddress 结构化结果

纯本地实现，无 ML 依赖，无外部数据文件。
"""

import re
from dataclasses import dataclass, field
from typing import Optional

# ======================== 数据结构 ========================


@dataclass
class ParsedAddress:
    """结构化地址解析结果"""
    province: str = ""           # 省/直辖市（无后缀），如 "广东"、"北京"
    city: str = ""               # 市（无后缀），如 "深圳"、"北京"
    district: str = ""           # 区/县，如 "南山区"、"朝阳区"
    development_zone: str = ""   # 开发区/高新区/自贸区/新区，如 "亦庄经济开发区"
    township: str = ""           # 街道/镇/乡，如 "望京街道"
    road: str = ""               # 路/街/大道/巷/弄，如 "望京西路"
    community: str = ""          # 小区/花园/苑/公寓，如 "望京花园东区"
    landmark: str = ""           # 地标/公司/大厦，如 "京东总部"、"万达广场"
    building: str = ""           # 栋/号楼/座，如 "3号楼"
    unit: str = ""               # 单元/门，如 "2单元"
    room: str = ""               # 室/层/楼，如 "501室"
    detail: str = ""             # 其余未匹配的文本
    raw: str = ""                # 原始地址字符串

    @property
    def full_detail(self) -> str:
        """拼接完整的详细地址（开发区+街道+路+小区+地标+栋+单元+室+剩余）。"""
        parts = []
        if self.development_zone:
            parts.append(self.development_zone)
        if self.township:
            parts.append(self.township)
        if self.road:
            parts.append(self.road)
        if self.community:
            parts.append(self.community)
        if self.landmark:
            parts.append(self.landmark)
        if self.building:
            parts.append(self.building)
        if self.unit:
            parts.append(self.unit)
        if self.room:
            parts.append(self.room)
        if self.detail:
            parts.append(self.detail)
        return "".join(parts)

    @property
    def full_address(self) -> str:
        """拼接完整地址字符串。"""
        parts = []
        if self.province:
            if self.province in MUNICIPALITIES:
                parts.append(self.province + "市")
            else:
                parts.append(self._add_suffix(self.province, "省"))
        if self.city and self.city != self.province:
            parts.append(self._add_suffix(self.city, "市"))
        if self.district:
            parts.append(self.district)
        detail = self.full_detail
        if detail:
            parts.append(detail)
        return "".join(parts)

    @staticmethod
    def _add_suffix(name: str, default_suffix: str) -> str:
        """给地名补上后缀（如果还没有的话）。"""
        if name.endswith(("省", "市", "自治区", "特别行政区", "区", "县")):
            return name
        return name + default_suffix


